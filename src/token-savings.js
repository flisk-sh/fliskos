import { readdir, open, stat } from "node:fs/promises";
import { join, relative, sep } from "node:path";

// The share of a project's text bytes that Flisk generated. This is a size estimate, not a token count or a measure of savings:
// tokens are approximated as bytes / 4, and only text files are counted. It says nothing about model usage.
const SKIP_DIRS = new Set(["node_modules", ".git", ".next", "dist", "build", "target", "__pycache__", ".venv"]);
const SKIP_FILES = new Set(["bun.lock", "bun.lockb", "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "Cargo.lock", "go.sum"]);
const MAX_FILE_BYTES = 512 * 1024;
const MAX_FILES = 5000;
const CACHE_MS = 60_000;
const CACHE_LIMIT = 200;

// Generated: any .autogenerated folder, Flisk's own output under .flisk/.flisk-out (.tdk/.tdk-out before the rename),
// and the root Tiltfile and docker-compose.yml.
export function isGeneratedPath(relativePath) {
  const parts = relativePath.split(sep);
  if (parts.includes(".autogenerated")) return true;
  if ((parts[0] === ".flisk" && parts[1] === ".flisk-out") || (parts[0] === ".tdk" && parts[1] === ".tdk-out")) return true;
  return parts.length === 1 && (parts[0] === "Tiltfile" || parts[0] === "docker-compose.yml");
}

async function isText(path) {
  const handle = await open(path, "r");
  try {
    const buffer = Buffer.alloc(512);
    const { bytesRead } = await handle.read(buffer, 0, buffer.length, 0);
    return !buffer.subarray(0, bytesRead).includes(0);
  } finally {
    await handle.close();
  }
}

// Walks the project asynchronously so the dashboard keeps answering. If the file cap is hit, the walk is partial, so no percentage is reported.
export async function measureTokenSavings(root) {
  let generated = 0;
  let authored = 0;
  let files = 0;
  let truncated = false;
  const visit = async (directory) => {
    let entries;
    try {
      entries = await readdir(directory, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      if (truncated) return;
      const path = join(directory, entry.name);
      if (entry.isDirectory()) {
        if (!SKIP_DIRS.has(entry.name)) await visit(path);
        continue;
      }
      if (!entry.isFile() || SKIP_FILES.has(entry.name)) continue;
      try {
        const { size } = await stat(path);
        if (size > MAX_FILE_BYTES || !(await isText(path))) continue;
        if (files >= MAX_FILES) {
          truncated = true;
          return;
        }
        const tokens = Math.ceil(size / 4);
        files += 1;
        if (isGeneratedPath(relative(root, path))) generated += tokens;
        else authored += tokens;
      } catch {}
    }
  };
  await visit(root);
  const total = generated + authored;
  return { generatedTokens: generated, authoredTokens: authored, savedPct: !truncated && total ? Math.round((generated / total) * 100) : null, truncated };
}

// One cache per server. Reads never wait for a walk: they return the last result (or null) and start a refresh in the background.
export function createTokenCache({ measure = measureTokenSavings, now = () => Date.now(), ttl = CACHE_MS, limit = CACHE_LIMIT } = {}) {
  const entries = new Map();
  return {
    get(root) {
      let entry = entries.get(root);
      if (!entry) {
        if (entries.size >= limit) entries.delete(entries.keys().next().value);
        entry = { at: -Infinity, value: null, pending: false };
        entries.set(root, entry);
      }
      if (!entry.pending && now() - entry.at >= ttl) {
        entry.pending = true;
        measure(root)
          .then((value) => { entry.value = value; })
          .catch(() => {})
          .finally(() => {
            entry.at = now();
            entry.pending = false;
          });
      }
      return entry.value;
    },
  };
}
